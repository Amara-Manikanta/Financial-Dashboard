/**
 * Writes ios/Kubera/Core/BenchmarkData.swift from src/utils/nifty50Data.js, so the
 * Nifty and fund-weight tables are never copied by hand.
 *   node ios/Tests/generate-benchmark.mjs
 * ParityTests checks the generated tables against the JS ones, so a stale file fails.
 */
import fs from 'fs';
import { NIFTY_50_STOCKS, NIFTY_NEXT_50_STOCKS, SBI_SMALL_CAP_WEIGHTS, HDFC_FLEXI_CAP_WEIGHTS } from '../../src/utils/nifty50Data.js';

const str = (v) => JSON.stringify(String(v));
const entry = (s) => `        BenchmarkStock(symbol: ${str(s.symbol)}, name: ${str(s.name)}, sector: ${str(s.sector ?? '')}, cap: ${s.cap ? str(s.cap) : 'nil'}, weight: ${typeof s.weight === 'number' ? s.weight : 'nil'}, aliases: [${(s.aliases || []).map(str).join(', ')}]),`;

const out = `// GENERATED by ios/Tests/generate-benchmark.mjs from src/utils/nifty50Data.js. Do not edit by hand:
// change the JavaScript and regenerate. Public market data only.

struct BenchmarkStock: Equatable {
    let symbol: String
    let name: String
    let sector: String
    let cap: String?
    let weight: Double?
    let aliases: [String]
}

enum BenchmarkData {
    static let nifty50: [BenchmarkStock] = [
${NIFTY_50_STOCKS.map(entry).join('\n')}
    ]

    static let niftyNext50: [BenchmarkStock] = [
${NIFTY_NEXT_50_STOCKS.map(entry).join('\n')}
    ]

    /// SBI Small Cap's holdings, in the order the source lists them.
    static let sbiSmallCap: [BenchmarkStock] = [
${Object.values(SBI_SMALL_CAP_WEIGHTS).map(entry).join('\n')}
    ]

    /// HDFC Flexi Cap's weights by symbol, in the order the source lists them.
    static let hdfcFlexiCapWeights: [(symbol: String, weight: Double)] = [
${Object.entries(HDFC_FLEXI_CAP_WEIGHTS).map(([k, v]) => `        (${str(k)}, ${v}),`).join('\n')}
    ]

    /// The master list the market-cap lookup walks.
    static let all: [BenchmarkStock] = nifty50 + niftyNext50 + sbiSmallCap
}
`;
fs.writeFileSync(new URL('../Kubera/Core/BenchmarkData.swift', import.meta.url), out);
console.log(`BenchmarkData.swift: ${NIFTY_50_STOCKS.length} + ${NIFTY_NEXT_50_STOCKS.length} + ${Object.keys(SBI_SMALL_CAP_WEIGHTS).length} stocks, ${Object.keys(HDFC_FLEXI_CAP_WEIGHTS).length} fund weights`);

// The built-in expense categories (utils/categories.js) become CategoryData.swift, in their own order.
import { CATEGORY_MAP } from '../../src/utils/categories.js';
const sw = (v) => JSON.stringify(String(v));
fs.writeFileSync(new URL('../Kubera/Core/CategoryData.swift', import.meta.url), `// GENERATED by ios/Tests/generate-benchmark.mjs from src/utils/categories.js. Do not edit by hand:
// change the JavaScript and regenerate.

enum CategoryData {
    /// Main categories and their sub-categories, in the order the Mac app lists them.
    static let map: [(main: String, subs: [String])] = [
${Object.entries(CATEGORY_MAP).map(([m, subs]) => `        (${sw(m)}, [${subs.map(sw).join(', ')}]),`).join('\n')}
    ]
}
`);
console.log(`CategoryData.swift: ${Object.keys(CATEGORY_MAP).length} categories`);
